"""
Builds src/styles/v3-dash-web.css: the phone (light) design of the Dashboard for wider screens.
Takes the colour/surface rules of v3-dash-phone.css (inside «max-width: 767px»), drops the phone-only layout ones,
scopes them to the Dashboard page, and appends the web layout from scripts/dash-web-extra.css.
Run after changing the phone styles or the extra file:
  python3 scripts/dash-web-css.py
"""
import re
from pathlib import Path

root = Path(__file__).resolve().parent.parent
styles = root / 'src' / 'styles'
SRC = ['v3-dash-phone.css']
# phone-only layout: the bottom-sheet period list, the title row, the slim AI row, the 6-month retention strip, modal actions stacked
DROP_SEL = re.compile(r'v3-pm-|v3-hero|v3-chips|v3-period-wrap|v3-period-btn|v3-bt-rfb|v3-ret-mini|v3-ret-mobile|v3-kpi-ai\b|v3-kpi\.v3-kpi-ai|v3-modal-actions|v3-bar-pop\b(?!-)|v3-chart-card \.v3-card-head|v3-chart-tools|v3-chart-card \.v3-seg|v3-chart-total \{|v3-risk-all|v3-mw-skel|body:has|v3-shell|v3-stars')
DROP_DECL = re.compile(r'^\s*(width|max-width|grid-template-columns|flex-direction|margin-top)\s*:')
SCOPE = 'body:has(.v3-dash)'
out = []

def blocks(css: str):
    """Yield (prelude, body) of top-level @media blocks; comments removed."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i = 0
    while True:
        m = re.compile(r'@media([^{]*)\{').search(css, i)
        if not m:
            return
        depth, j = 1, m.end()
        while depth:
            depth += {'{': 1, '}': -1}.get(css[j], 0); j += 1
        yield m.group(1), css[m.end():j - 1]
        i = j

for name in SRC:
    for pre, body in blocks((styles / name).read_text()):
        if not re.search(r'max-width:\s*767px', pre) or 'min-width' in pre:
            continue
        for sel, content in re.findall(r'([^{}]+)\{([^{}]*)\}', body):
            sels = [x.strip() for x in sel.split(',') if x.strip()]
            sels = [x for x in sels if not DROP_SEL.search(x)]
            if not sels:
                continue
            decls = [d.strip() for d in content.split(';') if d.strip()]
            mw = any('v3-mw' in x or 'v3-modal' in x for x in sels)  # «Матчі за 7 днів» and the dialogs keep their own layout
            decls = [d for d in decls if mw or not DROP_DECL.match(d)]
            if decls:
                out.append('  ' + ', '.join(f'{SCOPE} {x}' for x in sels) + ' { ' + '; '.join(decls) + '; }')

extra = (root / 'scripts' / 'dash-web-extra.css').read_text()
head = '/* GENERATED by scripts/dash-web-css.py — the light (phone) design of the Dashboard on wider screens, plus scripts/dash-web-extra.css. Do not edit by hand. */\n'
(styles / 'v3-dash-web.css').write_text(head + '@media (min-width: 768px) {\n' + '\n'.join(out) + '\n}\n' + extra)
print(len(out), 'rules')
