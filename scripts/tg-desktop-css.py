"""
Builds src/styles/v3-tg-desktop.css: the phone styles of the Telegram screen (rules inside «max-width: 767px»
of the stylesheets it uses) for wider screens too, scoped to the Telegram page — so the web version is the same
light design as the phone, in a centred column, its sheets centred. Run after changing those phone styles:
  python3 scripts/tg-desktop-css.py
"""
import re, tinycss2
from pathlib import Path

SRC = ['v3-compact.css', 'v3-drawer.css', 'v3-pay-phone.css', 'v3-matches-phone.css', 'v3-tg.css']
KEEP = re.compile(r'\.v3-(tg|mxp-|sheet|pay-sheet|pay-tabs|pay-tab|pill|skel|ad-tgav|pay-note|sum|sums|pay-sums|mx-sums|page|pay\b|ropt|btn)')
DROP = re.compile(r'v3-shell|v3-top|v3-nav|v3-drawer|v3-tabbar|v3-burger|\bnav\b|\bhtml\b|\bbody\b|:root|v3-mx-(?!sums|rf)|v3-mxw|v3-users|v3-dash|v3-bets|v3-ads|v3-audit|v3-support|v3-settings|v3-pay-(?!sheet|tab|note|sums)')
SCOPE = 'body:has(.v3-tg)'
root = Path(__file__).resolve().parent.parent / 'src' / 'styles'
out = []

def phone(prelude: str) -> bool:
    p = tinycss2.serialize(prelude)
    return 'max-width' in p and re.search(r'max-width:\s*7(67|68)px', p) is not None and 'min-width' not in p

def scope(sel: str) -> str:
    parts = [s.strip() for s in sel.split(',')]
    keep = [s for s in parts if KEEP.search(s) and not DROP.search(s)]
    return ', '.join(f'{SCOPE} {s}' for s in keep)

for name in SRC:
    css = (root / name).read_text()
    for rule in tinycss2.parse_stylesheet(css, skip_comments=True, skip_whitespace=True):
        if rule.type != 'at-rule' or rule.lower_at_keyword != 'media' or not phone(rule.prelude) or rule.content is None:
            continue
        for r in tinycss2.parse_rule_list(rule.content, skip_comments=True, skip_whitespace=True):
            if r.type != 'qualified-rule':
                continue
            sel = scope(tinycss2.serialize(r.prelude).strip())
            if sel:
                out.append(f'  {sel} {{{tinycss2.serialize(r.content).strip()}}}')

head = '/* GENERATED by scripts/tg-desktop-css.py — the phone design of the Telegram screen on wider screens. Do not edit by hand. */\n'
extra = f'''
  /* the page: a light background, a centred column the width of a large phone */
  body:has(.v3-tg), body:has(.v3-tg) .v3-shell {{ background: #e9ecf2; }}
  body:has(.v3-tg) .v3-stars {{ display: none; }}
  {SCOPE} .v3-tg {{ max-width: 640px; margin-left: auto; margin-right: auto; color: #11151c; }}
  {SCOPE} .v3-tg h1, {SCOPE} .v3-tg .v3-page-sub {{ color: #11151c; }}
  /* sheets: a centred panel, not a full-width bottom sheet */
  {SCOPE} .v3-sheet {{ left: 50% !important; right: auto !important; width: min(560px, 100vw) !important; transform: translateX(-50%) !important; }}
'''
(root / 'v3-tg-desktop.css').write_text(head + '@media (min-width: 768px) {\n' + extra + '\n'.join(out) + '\n}\n')
print(len(out), 'rules')
